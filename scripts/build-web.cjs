const { readdirSync, readFileSync, renameSync, writeFileSync } = require('node:fs');
const { extname, join, resolve } = require('node:path');
const { build } = require('esbuild');

const root = resolve(__dirname, '..');
const source = join(root, 'src');
const assetTypes = {
  '.md': 'text/plain;charset=utf-8',
  '.mp3': 'audio/mpeg',
  '.mp4': 'video/mp4',
  '.png': 'image/png',
  '.svg': 'image/svg+xml',
  '.ttf': 'font/ttf',
  '.wav': 'audio/wav'
};

function collectAssets(directory = '') {
  const assets = [];
  for (const entry of readdirSync(join(source, 'assets', directory), { withFileTypes: true })) {
    const path = directory + entry.name;
    if (entry.isDirectory()) {
      assets.push(...collectAssets(path + '/'));
      continue;
    }
    const type = assetTypes[extname(path)];
    if (!type) throw new Error('Unsupported FCA asset type: ' + path);
    const bytes = readFileSync(join(source, 'assets', path));
    assets.push([path, [type, bytes.toString(type === 'image/svg+xml' ? 'utf8' : 'base64')]]);
  }
  return assets;
}

async function buildWeb() {
  const bundle = await build({
    absWorkingDir: source,
    stdin: {
      contents: "import './browser.js';\nimport './game.js';\nimport './startup.js';",
      resolveDir: source
    },
    bundle: true,
    write: false,
    format: 'iife'
  });
  const assets = JSON.stringify(Object.fromEntries(collectAssets())).replace(/</g, '\\u003c');
  const script = bundle.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
  const browserStyle = readFileSync(join(source, 'browser.css'), 'utf8');
  const html = readFileSync(join(source, 'index.html'), 'utf8')
    .replace('<!doctype html>', '<!doctype html>\n<!-- Generated by npm run build:web -->')
    .replace(/<link rel="stylesheet" href="\.\/([^"]+)">/g, (_tag, path) =>
      '<style data-fca-stylesheet>\n' + readFileSync(join(source, path), 'utf8') + '\n</style>')
    .replace('</head>', '<style>\n' + browserStyle + '\n</style>\n</head>')
    .replace(/<object\b([^>]*?)\bdata="\.\/assets\/([^"]+)"([^>]*)><\/object>/g,
      (_tag, before, path, after) =>
        '<iframe' + before + 'data-fca-artwork="' + path + '"' +
        after.replace(/\s+type="image\/svg\+xml"/g, '') + '></iframe>')
    .replace(/(<(?:audio|video)\b[^>]*?)\bsrc="\.\/assets\/([^"]+)"/g,
      '$1data-fca-media="$2"')
    .replace(/(<div id="startup-intro"[^>]*>)/, '$1\n    <button id="fca-start-game" type="button" hidden>开始游戏</button>')
    .replace(/  <script type="module" src="\.\/[^"]+"><\/script>\r?\n/g, '')
    .replace('</body>', () =>
      '<script id="fca-embedded-assets" type="application/json">' + assets + '</script>\n' +
      '<script>\n' + script + '\n</script>\n</body>');

  const output = join(root, 'index.html');
  const temporary = output + '.tmp';
  writeFileSync(temporary, html, 'utf8');
  renameSync(temporary, output);
  console.log('Built index.html (' + (Buffer.byteLength(html) / 1024 ** 2).toFixed(1) + ' MiB)');
}

buildWeb().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
